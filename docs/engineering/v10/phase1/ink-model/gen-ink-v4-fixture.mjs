// B2.3 存下的墨迹（Ink v4 原始点）回放一致性夹具：ink-v4-fixture.json。
//
// 每个用例 = 一份 src/core/ink-math.js encodeInkRaw 编出的墨迹 + 它应当解出的东西：
//   rows   每笔的 encodeRawStrokes 行（打包串解开后逐个整数相同）
//   raw    decodeInkRaw 的原始点（x / y 0.1 单位、t 为整份墨迹的累计 ms、p）
//   ref    参考实现（reference.mjs，ink-model-1.0）对解出的原始点逐笔算出的 len / 样本数 / 并集面积 / 端帽 / 洇墨数
//   written  同一参考实现对「书写时」原始点（编码前、未量化）算出的并集面积——回放与书写时的差只来自 0.1 单位 / 1ms 量化
// 核对的两边：
//   · node test/core/ink-v4.test.mjs：重新生成必须与提交的文件逐字相同（编码、解码、参考实现任一变了都要重跑并提交）；
//     并断言 ref 与 written 的面积差 ≤ 1%（回放 ≈ 书写时）。
//   · XCTest ShiziWriteTests/InkSurfaceTests：Swift InkStoredInk.decode 解出的原始点与 raw 逐点相同、rows 相同；
//     InkModel 对解出的原始点算出的 len / 面积 / 端帽 / 洇墨与 ref 一致（同 InkModelCheck 的 1e-6 口径）——即原生回放 = JS 参考实现。
// 用法：node docs/engineering/v10/phase1/ink-model/gen-ink-v4-fixture.mjs  → 写 ink-v4-fixture.json
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { analyze, geometry, unionArea, MODEL_VERSION } from './reference.mjs';
import { decodeInkRaw, encodeInkRaw, inkRawRows } from '../../../../../src/core/ink-math.js';

const HERE = dirname(fileURLToPath(import.meta.url));
export const FIXTURE_PATH = join(HERE, 'ink-v4-fixture.json');

const r9 = x => (x === null || x === undefined ? null : Number(x.toPrecision(12)));

function summary(points) {
  const pr = analyze(points);
  const g = geometry(pr);
  return { len: r9(pr.len), n: pr.samples.length, area: r9(unionArea(g, 0.1)), capEnd: pr.caps.end.type, blooms: pr.blooms.length };
}

function caseOf(id, strokes) {
  const ink = encodeInkRaw(strokes, { maxStrokes: 36 });
  const raw = decodeInkRaw(ink);
  return {
    id,
    ink,
    rows: inkRawRows(ink),
    raw: raw.map(st => st.map(p => (p.p === undefined ? [r9(p.x), r9(p.y), p.t] : [r9(p.x), r9(p.y), p.t, r9(p.p)]))),
    ref: raw.map(summary),
    written: strokes.map(st => r9(unionArea(geometry(analyze(st)), 0.1))),
  };
}

export function buildFixture() {
  const doc = JSON.parse(readFileSync(join(HERE, 'vectors.json'), 'utf8'));
  const vec = id => doc.vectors.find(v => v.id === id);
  const pts = v => v.points.map(p => {
    const q = { x: p.x, y: p.y, t: p.t };
    if (p.p > 0) q.p = p.p;
    return q;
  });
  const cases = doc.vectors.filter(v => v.points && v.points.length).map(v => caseOf(v.id, [pts(v)]));
  // 多笔：横、竖钩、Pencil 竖，笔间停顿 240 / 610ms（g 还原笔间时间）
  const shift = (stroke, dt) => stroke.map(p => ({ ...p, t: p.t + dt }));
  const a = pts(vec('V01-heng-slow'));
  const b = pts(vec('V11-shugou'));
  const c = pts(vec('V13-pencil-shu'));
  const tb = a[a.length - 1].t + 240 - b[0].t;
  const b2 = shift(b, tb);
  const tc = b2[b2.length - 1].t + 610 - c[0].t;
  cases.push(caseOf('M01-three-strokes', [a, b2, shift(c, tc)]));
  return { model: MODEL_VERSION, note: 'generated by gen-ink-v4-fixture.mjs — do not edit by hand', cases };
}

export function fixtureText() {
  return JSON.stringify(buildFixture(), null, 1) + '\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(FIXTURE_PATH, fixtureText());
  console.log(`wrote ${FIXTURE_PATH}`);
}
